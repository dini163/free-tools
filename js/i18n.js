// Global localization controller functions
(function() {
    // 1. Determine active language (LocalStorage -> Browser Locale -> Default 'en')
    let lang = localStorage.getItem('lang');
    if (!lang) {
        const browserLang = navigator.language || navigator.userLanguage || 'en';
        // Match base formats
        if (browserLang.startsWith('zh-TW') || browserLang.startsWith('zh-HK') || browserLang.startsWith('zh-Hant')) {
            lang = 'zh-TW';
        } else if (browserLang.startsWith('zh')) {
            lang = 'zh-CN';
        } else {
            const base = browserLang.substring(0, 2).toLowerCase();
            lang = TRANSLATIONS[base] ? base : 'en';
        }
    }
    
    // Set document lang attribute
    document.documentElement.setAttribute('lang', lang);
    
    // Apply translations directly in synchronous phase if DOM nodes are already parsed
    // Otherwise we wait for DOMContentLoaded
    function translateDOM() {
        const currentLang = localStorage.getItem('lang') || lang;
        const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
        
        // Translate all data-i18n elements
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) {
                // If the element is an input button or has specific node requirements
                if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
                    el.value = dict[key];
                } else {
                    el.textContent = dict[key];
                }
            }
        });
        
        // Translate all data-i18n-placeholder elements
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (dict[key]) {
                el.setAttribute('placeholder', dict[key]);
            }
        });

        // Set Canonical or Document titles dynamically if there's a title mapping
        const pageTitleKey = document.documentElement.getAttribute('data-title-key');
        if (pageTitleKey && dict[pageTitleKey]) {
            document.title = dict[pageTitleKey] + " - FreeDevTools";
        }
    }

    // Expose toggle functions globally
    window.toggleLangMenu = function(event) {
        if (event) event.stopPropagation();
        const menu = document.getElementById('langMenu');
        if (menu) menu.classList.toggle('active');
    };

    window.changeLanguage = function(newLang) {
        localStorage.setItem('lang', newLang);
        document.documentElement.setAttribute('lang', newLang);
        translateDOM();
        updateLangUI(newLang);
        const menu = document.getElementById('langMenu');
        if (menu) menu.classList.remove('active');
        
        // Re-dispatch events for tools that might depend on loaded language text
        window.dispatchEvent(new Event('languagechange'));
    };

    function updateLangUI(currentLang) {
        const items = document.querySelectorAll('.lang-menu-item');
        items.forEach(item => {
            const action = item.getAttribute('onclick');
            if (action && action.includes(`'${currentLang}'`)) {
                item.classList.add('active');
            } else {
                item.classList.remove('active');
            }
        });
    }

    // Initialize translations on DOM load
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = localStorage.getItem('lang') || lang;
        translateDOM();
        updateLangUI(currentLang);
        
        // Close menu on outer click
        document.addEventListener('click', () => {
            const menu = document.getElementById('langMenu');
            if (menu) menu.classList.remove('active');
        });
    });
})();
